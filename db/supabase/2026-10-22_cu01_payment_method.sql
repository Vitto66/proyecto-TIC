-- CU-01 paso 3: medio de pago opcional del turista (se usa en CU-15).
-- Solo CREA una tabla nueva: no modifica ni borra tablas ni datos existentes.
-- Correr una sola vez en el SQL Editor de Supabase ANTES de levantar la app con el
-- perfil "postgres" (si no, ddl-auto=validate avisa que falta la tabla y no arranca).
--
-- Nunca se guarda el número de tarjeta ni el código de seguridad: solo el token que
-- devuelve el servicio de pagos, la marca, los últimos 4 dígitos y el vencimiento.

CREATE TABLE IF NOT EXISTS payment_method (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tourist_id   BIGINT       NOT NULL REFERENCES tourist (user_id),
    token        VARCHAR(100) NOT NULL UNIQUE,
    brand        VARCHAR(20)  NOT NULL CHECK (brand IN ('VISA', 'MASTERCARD', 'AMEX', 'OTHER')),
    last4        VARCHAR(4)   NOT NULL CHECK (last4 ~ '^[0-9]{4}$'),
    expiry_month INTEGER      NOT NULL CHECK (expiry_month BETWEEN 1 AND 12),
    expiry_year  INTEGER      NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_payment_method_tourist ON payment_method (tourist_id);
